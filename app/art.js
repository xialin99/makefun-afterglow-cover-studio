    shape('#fa9776',[[329,280],[384,229],[463,220],[517,189],[555,244],[563,351],[531,428],[479,477],[408,455],[361,412],[333,358]]);
    shape('#c36567',[[513,222],[555,244],[563,351],[531,428],[479,477],[455,449],[501,406],[513,356],[496,300]]);
